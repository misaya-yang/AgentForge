//! Canonical endpoint templates ported from the existing TypeScript API clients.
//! Request body defaults/validation stay with each backend; no mutation is implied
//! by listing a route. Query values are supplied separately and URL encoded.
use super::api::{ApiError, ApiRequest, DesktopApi};
use reqwest::Method;
use serde_json::Value;
use std::collections::BTreeMap;
#[derive(Clone, Copy, Debug)]
pub struct EndpointDefinition {
    pub area: &'static str,
    pub operation: &'static str,
    pub method: &'static str,
    pub template: &'static str,
}
impl EndpointDefinition {
    pub fn request(
        &self,
        parameters: &BTreeMap<String, String>,
        query: Vec<(String, String)>,
        body: Option<Value>,
    ) -> Result<ApiRequest, ApiError> {
        let mut segments = Vec::new();
        for segment in self.template.trim_start_matches('/').split('/') {
            let mut expanded = String::new();
            let mut remaining = segment;
            while let Some(start) = remaining.find('{') {
                expanded.push_str(&remaining[..start]);
                let tail = &remaining[start + 1..];
                let end = tail.find('}').ok_or(ApiError::Request)?;
                let value = parameters.get(&tail[..end]).ok_or(ApiError::Request)?;
                if value.is_empty()
                    || value.contains(['/', '\\', '\r', '\n', '\0'])
                    || value == "."
                    || value == ".."
                {
                    return Err(ApiError::Request);
                }
                expanded.push_str(value);
                remaining = &tail[end + 1..];
            }
            expanded.push_str(remaining);
            segments.push(expanded);
        }
        let method = Method::from_bytes(self.method.as_bytes()).map_err(|_| ApiError::Request)?;
        Ok(ApiRequest {
            method,
            segments,
            query,
            body,
            headers: Vec::new(),
        })
    }
    pub async fn execute(
        &self,
        api: &DesktopApi,
        parameters: &BTreeMap<String, String>,
        query: Vec<(String, String)>,
        body: Option<Value>,
    ) -> Result<Value, ApiError> {
        api.execute(self.request(parameters, query, body)?).await
    }
}
