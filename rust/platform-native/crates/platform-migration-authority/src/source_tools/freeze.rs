pub fn normalize_pg_dump(raw: &str) -> Result<String> {
    let skip=regex::Regex::new(r"(?i)^(--|\\|SET\s+|SELECT pg_catalog\.set_config|CREATE EXTENSION\b|COMMENT ON EXTENSION\b|CREATE SCHEMA\b|ALTER SCHEMA\b.*\bOWNER TO\b)").unwrap();
    let mut lines = Vec::new();
    for line in raw.lines() {
        let line = line.trim_end();
        if skip.is_match(line)
            || (line.is_empty() && lines.last().is_none_or(|v: &&str| v.is_empty()))
        {
            continue;
        }
        lines.push(line);
    }
    while lines.last().is_some_and(|s| s.is_empty()) {
        lines.pop();
    }
    let body = lines.join("\n") + "\n";
    let upper = body.to_uppercase();
    if [
        "OWNER TO",
        "GRANT ",
        "REVOKE ",
        "CREATE DATABASE",
        "DROP DATABASE",
    ]
    .iter()
    .chain(LEDGERS.iter())
    .any(|s| upper.contains(&s.to_uppercase()))
    {
        return Err(fail("normalized init contains forbidden dump constructs"));
    }
    if !upper.contains("CREATE TABLE") {
        return Err(fail("normalized init contains no tables"));
    }
    Ok(format!(
        "-- Generated by freeze-baseline (Rust) from converged scratch PG.\n-- roles.sql and extensions.sql run before this owner-executed file.\n\nSET LOCAL check_function_bodies = false;\n\n{body}"
    ))
}
const PG_QUERY: &[(&str, &str)] = &[
    ("application_name", "PGAPPNAME"),
    ("channel_binding", "PGCHANNELBINDING"),
    ("connect_timeout", "PGCONNECT_TIMEOUT"),
    ("gssencmode", "PGGSSENCMODE"),
    ("options", "PGOPTIONS"),
    ("sslcert", "PGSSLCERT"),
    ("sslcrl", "PGSSLCRL"),
    ("sslkey", "PGSSLKEY"),
    ("sslmode", "PGSSLMODE"),
    ("sslrootcert", "PGSSLROOTCERT"),
    ("target_session_attrs", "PGTARGETSESSIONATTRS"),
];
fn decode(s: &str) -> Result<String> {
    percent_encoding::percent_decode_str(s)
        .decode_utf8()
        .map(|v| v.into_owned())
        .map_err(|_| fail("source URI contains invalid encoding"))
}
pub fn dump_environment(dsn: &str) -> Result<BTreeMap<String, String>> {
    let uri = url::Url::parse(dsn).map_err(|_| fail("source DSN is not a valid PostgreSQL URI"))?;
    if !["postgres", "postgresql"].contains(&uri.scheme()) {
        return Err(fail("source DSN must be a PostgreSQL URI"));
    }
    let database = decode(uri.path().trim_start_matches('/'))?;
    if database.is_empty() {
        return Err(fail("source DSN must name a database"));
    }
    let mut result: BTreeMap<_, _> = std::env::vars().collect();
    for name in ["PGDATABASE", "PGHOST", "PGPASSWORD", "PGPORT", "PGUSER"]
        .iter()
        .copied()
        .chain(PG_QUERY.iter().map(|p| p.1))
    {
        result.remove(name);
    }
    result.insert("PGDATABASE".into(), database);
    if let Some(host) = uri.host_str() {
        result.insert("PGHOST".into(), decode(host)?);
    }
    if let Some(port) = uri.port() {
        result.insert("PGPORT".into(), port.to_string());
    }
    if !uri.username().is_empty() {
        result.insert("PGUSER".into(), decode(uri.username())?);
    }
    if let Some(pass) = uri.password() {
        result.insert("PGPASSWORD".into(), decode(pass)?);
    }
    for (k, v) in uri.query_pairs() {
        if let Some((_, key)) = PG_QUERY.iter().find(|p| p.0 == k) {
            result.insert((*key).into(), v.into_owned());
        }
    }
    Ok(result)
}
fn dump(root: &Path, dsn: &str, binary: &str) -> Result<String> {
    let mut command = Command::new(binary);
    command
        .current_dir(root)
        .env_clear()
        .envs(dump_environment(dsn)?)
        .args([
            "--schema-only",
            "--no-owner",
            "--no-privileges",
            "--no-comments",
            "--no-security-labels",
            "--no-publications",
            "--no-subscriptions",
        ]);
    for schema in ["public", "gateway", "assistant", "knowledge"] {
        command.args(["--schema", schema]);
    }
    for table in LEDGERS {
        command.args(["--exclude-table", &format!("public.{table}")]);
    }
    let result = command.output()?;
    if !result.status.success() {
        return Err(fail(
            "pg_dump failed; inspect a secret-safe local invocation",
        ));
    }
    normalize_pg_dump(
        &String::from_utf8(result.stdout).map_err(|_| fail("pg_dump output invalid UTF-8"))?,
    )
}
pub fn reference_specs() -> Vec<manifest::ReferenceDataSet> {
    serde_json::from_value(json!([
 {"table":"gateway.permissions","natural_key":["permission_code"],"immutable_columns":["name","description","category","resource","action","is_system"],"where":"is_system IS TRUE"},
 {"table":"gateway.rbac_roles","natural_key":["role_name"],"immutable_columns":["description","permissions","is_system"],"where":"is_system IS TRUE"},
 {"table":"gateway.role_permissions","natural_key":["role_name","permission_code"],"immutable_columns":["role_name","permission_code"],"where":"role_name IN (SELECT role_name FROM gateway.rbac_roles WHERE is_system IS TRUE)"}])).unwrap()
}
pub fn literal(value: &Value, array: bool) -> Result<String> {
    if value.is_null() {
        return Ok("NULL".into());
    }
    if array {
        let values = value
            .as_array()
            .ok_or_else(|| fail("reference array column returned a non-array"))?;
        let parts = values
            .iter()
            .map(|v| {
                v.as_str()
                    .map(|s| render_contract::sql_literal(s))
                    .ok_or_else(|| fail("reference array contains non-string"))
            })
            .collect::<Result<Vec<_>>>()?;
        return Ok(format!("ARRAY[{}]::varchar(100)[]", parts.join(", ")));
    }
    match value {
        Value::Bool(v) => Ok(if *v { "TRUE" } else { "FALSE" }.into()),
        Value::Number(v) if v.is_i64() || v.is_u64() => Ok(v.to_string()),
        Value::String(v) => Ok(render_contract::sql_literal(v)),
        _ => Err(fail("unsupported reference-data value type")),
    }
}
async fn reference_data(conn: &mut PgConnection) -> Result<String> {
    let mut lines = vec![
        "-- Generated by freeze-baseline (Rust); system-owned rows only.".into(),
        "-- Tenant/provider/model/rate-limit/admin-editable data is deliberately excluded.".into(),
        String::new(),
    ];
    for spec in reference_specs() {
        let mut columns = spec.natural_key.clone();
        for c in &spec.immutable_columns {
            if !columns.contains(c) {
                columns.push(c.clone());
            }
        }
        let columns_sql = columns.join(", ");
        let query = format!(
            "SELECT to_jsonb(reference_row) FROM (SELECT {columns_sql} FROM {} WHERE {} ORDER BY {}) reference_row",
            spec.table,
            spec.where_clause,
            spec.natural_key.join(", ")
        );
        let rows: Vec<Value> = sqlx::query_scalar(&query).fetch_all(&mut *conn).await?;
        if rows.is_empty() {
            return Err(fail("reference dataset has no protected system rows"));
        }
        let mut seen = BTreeSet::new();
        let mut rendered = Vec::new();
        for row in rows {
            let key = spec
                .natural_key
                .iter()
                .map(|c| row[c].clone())
                .collect::<Vec<_>>();
            if !seen.insert(serde_json::to_string(&key).unwrap()) {
                return Err(fail("reference dataset has duplicate natural keys"));
            }
            let values = columns
                .iter()
                .map(|c| {
                    literal(
                        &row[c],
                        spec.table == "gateway.rbac_roles" && c == "permissions",
                    )
                })
                .collect::<Result<Vec<_>>>()?;
            rendered.push(format!("({})", values.join(", ")));
        }
        lines.extend([
            format!("INSERT INTO {} ({columns_sql}) VALUES", spec.table),
            format!("    {};", rendered.join(",\n    ")),
            String::new(),
        ]);
    }
    Ok(lines.join("\n").trim_end().to_owned() + "\n")
}
async fn assert_database(conn: &mut PgConnection, name: &str) -> Result<String> {
    let row=sqlx::query("SELECT current_database()::text AS database_name,current_setting('server_version_num') AS version_num").fetch_one(conn).await?;
    let actual: String = row.try_get("database_name")?;
    let version: String = row.try_get("version_num")?;
    if actual != name || !version.starts_with("16") || !version.bytes().all(|c| c.is_ascii_digit())
    {
        return Err(fail(
            "DSN must target the declared PostgreSQL 16 scratch database",
        ));
    }
    let n: u32 = version
        .parse()
        .map_err(|_| fail("invalid PostgreSQL version"))?;
    Ok(format!("{}.{}", n / 10000, n % 10000))
}
fn serialize(v: &Value) -> Result<Vec<u8>> {
    let mut v = v.clone();
    v.sort_all_objects();
    let mut bytes = serde_json::to_vec_pretty(&v).map_err(|_| fail("cannot serialize manifest"))?;
    bytes.push(b'\n');
    Ok(bytes)
}
fn copy_tree(source: &Path, target: &Path) -> Result<()> {
    std::fs::create_dir_all(target)?;
    for entry in std::fs::read_dir(source)? {
        let entry = entry?;
        if entry.file_type()?.is_symlink() {
            return Err(fail("bootstrap tree must not contain symlinks"));
        }
        if entry.file_type()?.is_dir() {
            copy_tree(&entry.path(), &target.join(entry.file_name()))?;
        } else {
            std::fs::copy(entry.path(), target.join(entry.file_name()))?;
        }
    }
    Ok(())
}
pub async fn freeze(options: FreezeOptions) -> Result<()> {
    let root = options.root.canonicalize()?;
    let baseline = options.baseline_dir.canonicalize()?;
    if baseline
        != root
            .join("database/baselines")
            .join(DEFAULT_BASELINE_ID)
            .canonicalize()?
    {
        return Err(fail("output must be canonical baseline"));
    }
    if !run(
        &root,
        "git",
        &["status", "--porcelain=v1", "--untracked-files=normal"],
    )?
    .is_empty()
    {
        return Err(fail("baseline freeze requires a clean source commit"));
    }
    let sha = run(&root, "git", &["rev-parse", "HEAD"])?;
    let sha = sha.trim();
    if !regex::Regex::new("^[0-9a-f]{40}$").unwrap().is_match(sha) {
        return Err(fail("cannot resolve exact source commit"));
    }
    let path = baseline.join("manifest.json");
    let pending: Value = serde_json::from_slice(&std::fs::read(&path)?)
        .map_err(|_| fail("pending manifest invalid"))?;
    if pending["state"] != "pending-live-freeze" {
        return Err(fail(
            "source commit must carry pending-live-freeze manifest",
        ));
    }
    let relative = path
        .strip_prefix(&root)
        .map_err(|_| fail("manifest outside root"))?;
    let committed = run(
        &root,
        "git",
        &["show", &format!("HEAD:{}", relative.display())],
    )?;
    if serde_json::from_str::<Value>(&committed)
        .map_err(|_| fail("committed pending manifest invalid"))?
        != pending
    {
        return Err(fail("pending manifest differs from source HEAD"));
    }
    let generated = run(&root, "git", &["show", "-s", "--format=%cI", "HEAD"])?;
    if generated.trim().is_empty() {
        return Err(fail("source commit timestamp absent"));
    }
    let names = regex::Regex::new("^arc03_[a-z0-9_]{1,48}$").unwrap();
    if !names.is_match(&options.source_database)
        || !names.is_match(&options.verify_database)
        || options.source_database == options.verify_database
    {
        return Err(fail(
            "source and verification require distinct explicit arc03_* scratch database names",
        ));
    }
    let source_dsn = required("ARC03_FREEZE_SOURCE_MIGRATOR_DSN")?;
    let admin_dsn = required("ARC03_FREEZE_VERIFY_ADMIN_DSN")?;
    let verify_dsn = required("ARC03_FREEZE_VERIFY_MIGRATOR_DSN")?;
    let mut dsns = BTreeSet::new();
    for principal in credentials::ALL_PRINCIPALS {
        let dsn = credentials::dsn_for_principal(principal)?;
        if dsn == source_dsn
            || !dsns.insert(dsn.clone())
            || (*principal == "admin" && dsn != admin_dsn)
            || (*principal == "migrator" && dsn != verify_dsn)
        {
            return Err(fail(
                "freeze role DSNs must be distinct and match verification credentials",
            ));
        }
    }
    let version = run(&root, &options.pg_dump, &["--version"])?;
    let regex = regex::Regex::new(r"\b16(?:\.\d+)*\b").unwrap();
    let dump_version = regex
        .find(&version)
        .ok_or_else(|| fail("pg_dump 16 required"))?
        .as_str();
    let stage = Temporary::new()?;
    let (inventory, ownership, grants_policy) = super::policy::build(&root, Some(sha), false)?;
    let mut artifacts = BTreeMap::<String, Vec<u8>>::new();
    for (name, value) in [
        ("data-access-inventory.json", inventory),
        ("ownership-policy.json", ownership),
        ("grants-policy.json", grants_policy),
    ] {
        artifacts.insert(name.into(), super::policy::serialized(&value)?);
    }
    let grants = super::grants::generate(
        &artifacts["data-access-inventory.json"],
        &artifacts["grants-policy.json"],
        PREFIX,
    )?;
    artifacts.insert("grants.sql".into(), grants.into_bytes());
    let objects = render_contract::load_policy_bytes(
        &artifacts["data-access-inventory.json"],
        &artifacts["ownership-policy.json"],
    )?;
    let matrix = render_contract::load_grant_matrix(
        &artifacts["data-access-inventory.json"],
        &artifacts["grants-policy.json"],
    )?;
    let cutover = render_contract::replace_relocation(
        &std::fs::read_to_string(baseline.join("cutover_convergence.sql"))?,
        &render_contract::render_relocation(&objects),
    )?;
    let verify = render_contract::render_verify(&objects, &matrix)?;
    let verify_path = stage.0.join("verify.sql");
    std::fs::write(&verify_path, &verify)?;
    let paths = AuthorityPaths {
        database_dir: root.join("database"),
    };
    let mut source = PgConnection::connect(&source_dsn).await?;
    let mut admin = PgConnection::connect(&admin_dsn).await?;
    let pg_version = assert_database(&mut source, &options.source_database).await?;
    assert_database(&mut admin, &options.verify_database).await?;
    bootstrap::provision_roles_admin(&mut admin, &paths, PREFIX).await?;
    bootstrap::provision_extensions_admin(&mut admin, &paths).await?;
    bootstrap::verify_baseline_sql_file(&mut source, &verify_path, PREFIX).await?;
    let reference = reference_data(&mut source).await?;
    let fingerprints =
        fingerprint::compute_fingerprints(&mut source, PREFIX, &reference_specs()).await?;
    let init = dump(&root, &source_dsn, &options.pg_dump)?;
    source.close().await?;
    admin.close().await?;
    for (name, content) in [
        ("cutover_convergence.sql", cutover),
        ("verify.sql", verify),
        ("reference_data.sql", reference),
        ("init.sql", init),
    ] {
        artifacts.insert(name.into(), content.into_bytes());
    }
    let legacy =
        manifest::load_legacy_manifest(&root.join("database/migrations/legacy-manifest.yml"))?;
    let files: BTreeMap<_, _> = SQL_FILES
        .iter()
        .map(|name| (*name, hash(&artifacts[*name])))
        .collect();
    let policies: BTreeMap<_, _> = POLICY_FILES
        .iter()
        .map(|name| (*name, hash(&artifacts[*name])))
        .collect();
    let revision = legacy
        .freeze_point
        .get(..3)
        .ok_or_else(|| fail("invalid freeze point"))?
        .parse::<u32>()
        .map_err(|_| fail("invalid freeze point"))?
        .to_string();
    let payload = json!({"schema":manifest::BASELINE_SCHEMA,"state":"frozen","baseline_id":DEFAULT_BASELINE_ID,"schema_revision":revision,"source_git_sha":sha,"last_legacy_change":legacy.freeze_point,"structural_sha256":fingerprints["structural"],"acl_sha256":fingerprints["acl"],"extensions_sha256":fingerprints["extensions"],"reference_data_sha256":fingerprints["reference_data"],"generator":"rust/platform-native/crates/platform-migration-authority/src/source_tools/freeze.rs","generator_sha256":hash(include_bytes!("freeze.rs")),"generated_at":generated.trim(),"postgres_version":pg_version,"pg_dump_version":dump_version,"files_sha256":files,"policy_files_sha256":policies,"reference_data":reference_specs()});
    let manifest_bytes = serialize(&payload)?;
    let database_dir = stage.0.join("database");
    let staged_baseline = database_dir.join("baselines").join(DEFAULT_BASELINE_ID);
    std::fs::create_dir_all(&staged_baseline)?;
    copy_tree(&paths.bootstrap_dir(), &database_dir.join("bootstrap"))?;
    for (name, bytes) in &artifacts {
        std::fs::write(staged_baseline.join(name), bytes)?;
    }
    std::fs::write(staged_baseline.join("manifest.json"), &manifest_bytes)?;
    let frozen = manifest::load_baseline_manifest(&staged_baseline.join("manifest.json"))?;
    let mut verify_conn = PgConnection::connect(&verify_dsn).await?;
    assert_database(&mut verify_conn, &options.verify_database).await?;
    let reproduced = bootstrap::fresh_install(
        &mut verify_conn,
        &AuthorityPaths { database_dir },
        &frozen,
        &hash(&manifest_bytes),
        PREFIX,
    )
    .await?;
    verify_conn.close().await?;
    if reproduced != fingerprints {
        return Err(fail("verification fingerprints differ from source"));
    }
    credentials::verify_role_connections(PREFIX, Some(&options.verify_database)).await?;
    if !options.write {
        return Err(fail(
            "all live checks passed but --write absent; no files changed",
        ));
    }
    // Stage beside destination for atomic same-filesystem replacement; activation marker last.
    let publish = baseline.join(format!(".freeze-{}", uuid::Uuid::new_v4()));
    std::fs::create_dir(&publish)?;
    let cleanup = Temporary(publish);
    for (name, bytes) in &artifacts {
        std::fs::write(cleanup.0.join(name), bytes)?;
    }
    std::fs::write(cleanup.0.join("manifest.json"), manifest_bytes)?;
    for name in POLICY_FILES
        .iter()
        .chain(SQL_FILES.iter())
        .copied()
        .chain(["manifest.json"])
    {
        std::fs::rename(cleanup.0.join(name), baseline.join(name))?;
    }
    Ok(())
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn dump_noise_and_guards() {
        let sql = normalize_pg_dump(
            "-- noise\nSET x=y;\nCREATE SCHEMA gateway;\nCREATE TABLE gateway.x(id integer);\n",
        )
        .unwrap();
        assert!(sql.contains("CREATE TABLE gateway.x"));
        assert!(!sql.contains("CREATE SCHEMA"));
        assert!(
            normalize_pg_dump("CREATE TABLE x(id integer);\nGRANT SELECT ON x TO PUBLIC;").is_err()
        );
        assert!(normalize_pg_dump("CREATE TABLE schema_migrations(id integer);").is_err());
    }
    #[test]
    fn literal_and_uri() {
        assert_eq!(
            literal(&json!(["a'b", "x"]), true).unwrap(),
            "ARRAY['a''b', 'x']::varchar(100)[]"
        );
        assert!(literal(&json!(1.5), false).is_err());
        let env =
            dump_environment("postgres://test:p%40ss@localhost:5433/arc03_test?sslmode=require")
                .unwrap();
        assert_eq!(env["PGPASSWORD"], "p@ss");
        assert_eq!(env["PGDATABASE"], "arc03_test");
        assert_eq!(env["PGPORT"], "5433");
    }
}
