fn fail(s: &str) -> AuthorityError {
    AuthorityError::Refused(s.into())
}
fn hash(b: &[u8]) -> String {
    format!("{:x}", Sha256::digest(b))
}
fn required(name: &str) -> Result<String> {
    std::env::var(name)
        .ok()
        .filter(|s| !s.is_empty())
        .ok_or_else(|| fail(&format!("required environment variable {name} is absent")))
}
fn run(root: &Path, binary: &str, args: &[&str]) -> Result<String> {
    let out = Command::new(binary).args(args).current_dir(root).output()?;
    if !out.status.success() {
        return Err(fail(
            "external baseline operation failed; output withheld to protect credentials",
        ));
    }
    String::from_utf8(out.stdout).map_err(|_| fail("external operation returned invalid UTF-8"))
}
struct Temporary(PathBuf);
impl Temporary {
    fn new() -> Result<Self> {
        let p = std::env::temp_dir().join(format!("arc03-native-freeze-{}", uuid::Uuid::new_v4()));
        std::fs::create_dir(&p)?;
        Ok(Self(p))
    }
}
impl Drop for Temporary {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}
