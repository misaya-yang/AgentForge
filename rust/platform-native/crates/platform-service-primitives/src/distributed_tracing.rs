#[path = "telemetry_pipeline.rs"]
mod pipeline;
pub use opentelemetry_sdk::trace::SdkTracerProvider;
pub use pipeline::{TelemetryGuard, initialize_with_options};
#[derive(Clone)]
pub struct RequestId(pub String);
pub fn initialize(service_name: &'static str) -> TelemetryGuard {
    initialize_with_options(service_name, TracingOptions::default())
}
#[derive(Clone, Default)]
pub struct TracingOptions {
    pub otlp_endpoint: Option<String>,
    pub resource_attributes: Vec<KeyValue>,
}
impl TracingOptions {
    pub fn resolved_endpoint(&self) -> String {
        self.otlp_endpoint
            .clone()
            .unwrap_or_else(|| std::env::var("OTEL_EXPORTER_OTLP_ENDPOINT").unwrap_or_default())
    }
    pub fn resource(&self, service_name: &str) -> Resource {
        Resource::builder_empty()
            .with_attribute(KeyValue::new("service.name", service_name.to_owned()))
            .with_attribute(KeyValue::new("gen_ai.semconv.version", "1.37.0"))
            .with_attributes(self.resource_attributes.clone())
            .build()
    }
}

struct Headers<'a>(&'a HeaderMap);
impl Extractor for Headers<'_> {
    fn get(&self, key: &str) -> Option<&str> {
        self.0.get(key)?.to_str().ok()
    }
    fn keys(&self) -> Vec<&str> {
        self.0.keys().map(|key| key.as_str()).collect()
    }
}
/// Explicit equivalent of request.state traceparent/tracestate. This carrier is
/// generated by the SDK, never trusted as identity or used to modify signed headers.
#[derive(Clone, Debug, Default)]
pub struct TraceCarrier(pub HashMap<String, String>);
impl Injector for TraceCarrier {
    fn set(&mut self, key: &str, value: String) {
        self.0.insert(key.into(), value);
    }
}
pub fn current_carrier() -> TraceCarrier {
    let mut carrier = TraceCarrier::default();
    TraceContextPropagator::new().inject_context(&Context::current(), &mut carrier);
    carrier
}
pub async fn inbound(mut request: Request, next: Next) -> Response {
    let propagator = TraceContextPropagator::new();
    let parent = propagator.extract(&Headers(request.headers()));
    let tracer = global::tracer("ai_gateway_core.tracing");
    // Route templates are bounded and never contain query, tenant IDs or content.
    let route = request
        .extensions()
        .get::<axum::extract::MatchedPath>()
        .map(|p| p.as_str().to_owned())
        .unwrap_or_else(|| "unmatched".into());
    let method = match request.method().as_str() {
        "GET" => "GET",
        "POST" => "POST",
        "PUT" => "PUT",
        "DELETE" => "DELETE",
        "PATCH" => "PATCH",
        "HEAD" => "HEAD",
        "OPTIONS" => "OPTIONS",
        "TRACE" => "TRACE",
        "CONNECT" => "CONNECT",
        _ => "_OTHER",
    };
    let attributes = vec![
        KeyValue::new("http.request.method", method),
        KeyValue::new("http.route", route.clone()),
    ];
    let started = std::time::Instant::now();
    let span = tracer
        .span_builder(format!("{method} {route}"))
        .with_kind(SpanKind::Server)
        .with_attributes(attributes)
        .start_with_context(&tracer, &parent);
    let context = parent.with_span(span);
    let mut carrier = TraceCarrier::default();
    propagator.inject_context(&context, &mut carrier);
    request.extensions_mut().insert(carrier);
    // Context is attached on each poll, not across await on a thread-local guard.
    // The response body is returned untouched, including SSE and large downloads.
    let response = next.run(request).with_context(context.clone()).await;
    context.span().set_attribute(KeyValue::new(
        "http.response.status_code",
        response.status().as_u16() as i64,
    ));
    context
        .span()
        .set_status(if response.status().is_server_error() {
            Status::error("")
        } else {
            Status::Ok
        });
    let status = response.status().as_u16();
    let _active = context.clone().attach();
    global::meter("agentforge.http")
        .f64_histogram("http.server.request.duration")
        .with_unit("s")
        .build()
        .record(
            started.elapsed().as_secs_f64(),
            &[
                KeyValue::new("http.route", route.clone()),
                KeyValue::new("http.response.status_code", status as i64),
            ],
        );
    pipeline::request_finished(&context, status);
    context.span().end();
    response
}

#[cfg(test)]
mod tests {
    use super::*;
    use opentelemetry::trace::TracerProvider;
    #[tokio::test]
    async fn inbound_propagates_active_span_and_never_buffers_body() {
        use axum::{Router, body::Body, routing::get};
        use tower::ServiceExt;
        #[derive(Clone, Debug, Default)]
        struct Capture(std::sync::Arc<std::sync::Mutex<Vec<opentelemetry_sdk::trace::SpanData>>>);
        impl opentelemetry_sdk::trace::SpanExporter for Capture {
            async fn export(
                &self,
                batch: Vec<opentelemetry_sdk::trace::SpanData>,
            ) -> opentelemetry_sdk::error::OTelSdkResult {
                self.0.lock().unwrap().extend(batch);
                Ok(())
            }
        }
        let capture = Capture::default();
        let provider = SdkTracerProvider::builder()
            .with_simple_exporter(capture.clone())
            .build();
        global::set_tracer_provider(provider.clone());
        let app = Router::new()
            .route(
                "/stream/{private_id}",
                get(|request: Request| async move {
                    let carrier = request.extensions().get::<TraceCarrier>().unwrap();
                    assert_eq!(current_carrier().0, carrier.0);
                    assert!(
                        carrier.0["traceparent"]
                            .starts_with("00-4bf92f3577b34da6a3ce929d0e0e4736-")
                    );
                    assert_ne!(&carrier.0["traceparent"][36..52], "00f067aa0ba902b7");
                    assert_eq!(carrier.0["tracestate"], "vendor=value");
                    Response::builder()
                        .status(503)
                        .body(Body::from_stream(futures_util::stream::pending::<
                            Result<axum::body::Bytes, std::io::Error>,
                        >()))
                        .unwrap()
                }),
            )
            .layer(axum::middleware::from_fn(inbound));
        let request = Request::builder()
            .uri("/stream/private-path-value?token=private-query-value")
            .header("authorization", "Bearer private-credential-value")
            .header("user-agent", "private-user-agent-value")
            .header(
                "traceparent",
                "00-4bf92f3577b34da6a3ce929d0e0e4736-00f067aa0ba902b7-01",
            )
            .header("tracestate", "vendor=value")
            .body(Body::empty())
            .unwrap();
        let response =
            tokio::time::timeout(std::time::Duration::from_secs(1), app.oneshot(request))
                .await
                .unwrap()
                .unwrap();
        assert_eq!(response.status().as_u16(), 503);
        drop(response);
        provider.shutdown().unwrap();
        let spans = capture.0.lock().unwrap();
        assert_eq!(spans.len(), 1);
        assert_eq!(spans[0].name, "GET /stream/{private_id}");
        assert_eq!(spans[0].parent_span_id.to_string(), "00f067aa0ba902b7");
        let exported = format!("{:?}", spans[0]);
        for seed in [
            "private-path-value",
            "private-query-value",
            "private-credential-value",
            "private-user-agent-value",
        ] {
            assert!(!exported.contains(seed));
        }
        assert!(spans[0].events.events.is_empty());
    }
    #[test]
    fn parent_trace_and_sampling_survive_sdk_carrier() {
        for sampled in ["00", "01"] {
            let provider = SdkTracerProvider::builder()
                .with_sampler(Sampler::ParentBased(Box::new(Sampler::AlwaysOn)))
                .build();
            let mut headers = HeaderMap::new();
            headers.insert(
                "traceparent",
                format!("00-4bf92f3577b34da6a3ce929d0e0e4736-00f067aa0ba902b7-{sampled}")
                    .parse()
                    .unwrap(),
            );
            headers.insert("tracestate", "vendor=value".parse().unwrap());
            let propagator = TraceContextPropagator::new();
            let parent = propagator.extract(&Headers(&headers));
            let span = provider
                .tracer("test")
                .start_with_context("request", &parent);
            let context = parent.with_span(span);
            let mut carrier = TraceCarrier::default();
            propagator.inject_context(&context, &mut carrier);
            assert!(carrier.0["traceparent"].starts_with("00-4bf92f3577b34da6a3ce929d0e0e4736-"));
            assert!(carrier.0["traceparent"].ends_with(sampled));
            assert_eq!(carrier.0["tracestate"], "vendor=value");
            context.span().end();
            provider.shutdown().unwrap();
        }
    }
}
