pub fn extend_document(document: &mut Value) {
    let mut added = 0;
    for &(path, method, handler, source) in OPERATIONS {
        if document["paths"][path].get(method).is_some() {
            continue;
        }
        let parameters: Vec<Value> = path
            .split('/')
            .filter_map(|part| {
                part.strip_prefix('{').and_then(|v|v.strip_suffix('}')).map(|name|
                json!({"name":name,"in":"path","required":true,"schema":{"type":"string"}}))
            })
            .collect();
        document["paths"][path][method] = json!({
            "operationId":format!("native_{}_{}_{}_{}",source,handler,method,path.replace('/',"_").replace(['{','}'],"")),
            "parameters":parameters,
            "responses":{"default":{"description":"Native handler response; media type, schema and status alternatives not yet verified"}},
            "x-native-declaration":{"source":SOURCES[source].0,"handler":handler,"schema_verified":false,"route_verified":true}
        });
        added += 1;
    }
    document["x-native-route-registry"] = json!({
        "schema":"native-mounted-route-registry/v1", "added_opaque_operations":added,
        "complete":false,
        "unresolved_dispatchers":UNRESOLVED.iter().map(|(path,source)|json!({"path":path,"source":SOURCES[*source].0})).collect::<Vec<_>>(),
        "source_sha256":SOURCES.iter().map(|(name,text)|((*name).to_string(),json!(format!("{:x}",Sha256::digest(text.as_bytes()))))).collect::<serde_json::Map<String,Value>>()
    });
}
